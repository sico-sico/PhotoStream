/**
 * Synthetic photo libraries for the benchmarks.
 *
 * Two properties matter more than realism here:
 *
 * *Deterministic.* The same bytes on every run and every machine. Otherwise a
 * 5% difference could be the fixture rather than the code.
 *
 * *Distinct files.* Each photo is a real, separate file. An earlier version
 * hard-linked one template into 40 000 names to save space; concurrent reads of
 * the same inode do not scale, so every path to the same template cost about
 * 240 µs while a genuinely distinct file cost 60 µs. The benchmark would have
 * been measuring NTFS's per-file contention, not the scanner.
 *
 * Files are also deliberately larger than 64 KB. The scan reads a 64 KB prefix
 * and only walks the container when the read filled the window; tiny files would
 * take the "the file is shorter than the window" exit and never exercise the
 * code the benchmark exists to watch. Small enough to keep a 4 000-photo tree
 * around 360 MB, large enough to take the real path.
 *
 * Fixtures live outside the repository (in the OS temp directory by default) and
 * carry a marker file, so they are built once and reused until `FIXTURE_VERSION`
 * changes.
 */
import { createHash } from 'node:crypto'
import { copyFile, mkdir, readFile, rm, stat, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import sharp, { type Sharp } from 'sharp'
import type { Photo } from '../../src/shared/types'

/** Bumped when the generated bytes change; the marker triggers a rebuild. */
const FIXTURE_VERSION = 4

/** Files of each kind kept for the per-file metadata benchmarks. */
const SAMPLES_PER_KIND = 8

/** Photos per album in the recursive fixture. */
const ALBUMS = 4

export interface SampleFiles {
  /** A normal camera export: EXIF in the first few kilobytes. */
  jpegExif: string[]
  /** A screenshot or re-export with no EXIF at all. */
  jpegPlain: string[]
  /** A PNG screenshot: no EXIF, and metadata chunks before the image data. */
  pngPlain: string[]
  /** EXIF pushed past the 64 KB window, so the second read is exercised. */
  jpegFat: string[]
}

export interface BenchFixtures {
  root: string
  samples: SampleFiles
  /** 4 albums × 1 000 photos: the default library. */
  lib4000: string
  /** One album of `lib4000`: 1 000 files in a flat directory. */
  album1000: string
  /** 4 albums × 10 000 photos. Built on demand by `ensureLargeLibrary`. */
  lib40000: string
  /** A 12-megapixel original, for the thumbnail pipeline. */
  large: string
  /** Photo records matching `lib40000`, for the layout and IPC benchmarks. */
  photos40000: Photo[]
  /** Whether anything had to be (re)built on this run. */
  rebuilt: boolean
}

interface Marker {
  version: number
  kind: string
  files: number
}

async function markerMatches(dir: string, marker: Marker): Promise<boolean> {
  try {
    const found = JSON.parse(await readFile(join(dir, '.bench-fixture.json'), 'utf8')) as Marker
    return (
      found.version === marker.version &&
      found.kind === marker.kind &&
      found.files === marker.files
    )
  } catch {
    return false
  }
}

async function writeMarker(dir: string, marker: Marker): Promise<void> {
  await writeFile(join(dir, '.bench-fixture.json'), JSON.stringify(marker), 'utf8')
}

/** A JPEG segment with a 16-bit length field. */
function segment(marker: number, payload: Buffer): Buffer {
  const header = Buffer.alloc(4)
  header[0] = 0xff
  header[1] = marker
  header.writeUInt16BE(payload.length + 2, 2)
  return Buffer.concat([header, payload])
}

/** A PNG chunk, with its length, type and (unchecked) CRC. */
function chunk(type: string, payload: Buffer): Buffer {
  const header = Buffer.alloc(8)
  header.writeUInt32BE(payload.length, 0)
  header.write(type, 4, 'latin1')
  return Buffer.concat([header, payload, Buffer.alloc(4)])
}

/** Insert segments immediately after the start-of-image marker. */
function afterSoi(jpeg: Buffer, additions: readonly Buffer[]): Buffer {
  return Buffer.concat([jpeg.subarray(0, 2), ...additions, jpeg.subarray(2)])
}

/**
 * Image content with enough structure to encode to a realistic size.
 *
 * A flat colour would make a JPEG of a few kilobytes, which takes the "shorter
 * than the window" path and flatters everything downstream. Noise upscaled
 * smoothly lands around 60 KB at 640×480 — a believable small photo — while
 * staying deterministic and cheap to generate.
 */
async function photoContent(width: number, height: number): Promise<Sharp> {
  const tile = 192
  const raw = Buffer.allocUnsafe(tile * tile * 3)
  for (let y = 0; y < tile; y++) {
    for (let x = 0; x < tile; x++) {
      const index = (y * tile + x) * 3
      // A hash rather than a seeded RNG: identical bytes without carrying state.
      const hash = createHash('sha256').update(`${x},${y}`).digest()
      raw[index] = hash[0]
      raw[index + 1] = hash[1]
      raw[index + 2] = hash[2]
    }
  }
  return sharp(raw, { raw: { width: tile, height: tile, channels: 3 } }).resize(width, height, {
    kernel: 'cubic'
  })
}

/** Pad a JPEG past 64 KB without touching a pixel, so the walk runs. */
function padJpeg(jpeg: Buffer, bytes: number): Buffer {
  return afterSoi(jpeg, [segment(0xfe, Buffer.alloc(bytes, 0x20))])
}

async function templateDir(root: string): Promise<{ dir: string; built: boolean }> {
  const dir = join(root, '_templates')
  const marker: Marker = { version: FIXTURE_VERSION, kind: 'templates', files: 5 }
  if (await markerMatches(dir, marker)) return { dir, built: false }

  await rm(dir, { recursive: true, force: true })
  await mkdir(dir, { recursive: true })

  const exif = await (await photoContent(480, 360))
    .withExif({
      IFD0: { DateTime: '2019:06:15 10:20:30' },
      IFD3: { DateTimeOriginal: '2019:06:15 10:20:30' }
    })
    .jpeg({ quality: 78 })
    .toBuffer()
  // Just over 64 KB: above the window, with the EXIF in the first few kilobytes.
  // Size matters: the tree is 40 000 files in the largest case, and 150 KB each
  // would be 6 GB of temp for a scan that never reads past 64 KB of a file.
  await writeFile(join(dir, 'exif.jpg'), padJpeg(exif, 10_000))

  const plain = await (await photoContent(480, 360)).jpeg({ quality: 78 }).toBuffer()
  await writeFile(join(dir, 'plain.jpg'), padJpeg(plain, 10_000))

  // A screenshot: metadata chunks (`tEXt` here, `iCCP`/`eXIf` in the wild) come
  // before the image data, which is the moment the walk may declare itself done.
  // Keep the text chunk small enough that IDAT starts well inside the 64 KB
  // window: a PNG whose first chunk straddles the window boundary pays for a
  // second read, which is a real case but not the common one.
  const png = await (await photoContent(480, 360)).png({ compressionLevel: 6 }).toBuffer()
  await writeFile(join(dir, 'shot.png'), afterPngHeader(png, chunk('tEXt', Buffer.alloc(12_000, 0x41))))

  // 4 × 65 KB of APP2 ahead of the EXIF: the block now sits past the first read,
  // which is the only way to exercise the second one on purpose.
  await writeFile(
    join(dir, 'fat.jpg'),
    afterSoi(
      exif,
      Array.from({ length: 4 }, () => segment(0xe2, Buffer.alloc(65_000, 0x11)))
    )
  )

  // A 12-megapixel original, for feeding the thumbnail pipeline.
  await writeFile(
    join(dir, '12mp.jpg'),
    await (await photoContent(4000, 3000))
      .withExif({
        IFD0: { DateTime: '2021:03:04 05:06:07' },
        IFD3: { DateTimeOriginal: '2021:03:04 05:06:07' }
      })
      .jpeg({ quality: 88 })
      .toBuffer()
  )

  await writeMarker(dir, marker)
  return { dir, built: true }
}

/** Insert a chunk after the PNG signature, i.e. before IHDR's data. */
function afterPngHeader(png: Buffer, addition: Buffer): Buffer {
  return Buffer.concat([png.subarray(0, 8), addition, png.subarray(8)])
}

/** Which template a photo index uses, in a realistic mix. */
function templateFor(index: number): string {
  if (index % 50 === 0) return 'shot.png'
  if (index % 500 === 7) return 'fat.jpg'
  if (index % 10 === 1) return 'plain.jpg'
  return 'exif.jpg'
}

/**
 * Build `albums × perAlbum` distinct photo files under `dir`, or reuse them.
 *
 * Copies, not links: see the note at the top of this file. Copies are issued in
 * batches rather than one at a time, which is the difference between two seconds
 * and twenty on the first run of a clean checkout.
 */
async function library(
  root: string,
  templates: string,
  name: string,
  albums: number,
  perAlbum: number
): Promise<{ dir: string; built: boolean }> {
  const dir = join(root, name)
  const files = albums * perAlbum
  const marker: Marker = { version: FIXTURE_VERSION, kind: name, files }
  if (await markerMatches(dir, marker)) return { dir, built: false }

  await rm(dir, { recursive: true, force: true })
  await mkdir(dir, { recursive: true })

  const jobs: Array<{ source: string; target: string }> = []
  for (let album = 0; album < albums; album++) {
    const albumDir = join(dir, `album-${String(album).padStart(3, '0')}`)
    await mkdir(albumDir, { recursive: true })
    for (let index = 0; index < perAlbum; index++) {
      const absolute = album * perAlbum + index
      const template = templateFor(absolute)
      const extension = template.endsWith('.png') ? 'png' : 'jpg'
      jobs.push({
        source: join(templates, template),
        target: join(albumDir, `IMG_${String(absolute).padStart(5, '0')}.${extension}`)
      })
    }
  }

  let cursor = 0
  const worker = async (): Promise<void> => {
    for (;;) {
      const job = jobs[cursor]
      cursor += 1
      if (!job) return
      await copyFile(job.source, job.target)
    }
  }
  await Promise.all(Array.from({ length: 32 }, worker))

  await writeMarker(dir, marker)
  return { dir, built: true }
}

/** Deterministic photo records, matching the synthetic 40 000-photo library. */
export function syntheticPhotos(count: number): Photo[] {
  const photos: Photo[] = []
  for (let index = 0; index < count; index++) {
    const album = Math.floor(index / (count / 4))
    const year = 2005 + (index % 20)
    const month = 1 + (index % 12)
    const day = 1 + (index % 27)
    // A spread of aspect ratios, since the layout packs rows around them.
    const width = [6000, 4000, 3000, 2000, 1600][index % 5]
    const height = [4000, 3000, 4000, 1500, 1600][index % 5]
    photos.push({
      id: `photo-${index}`,
      path: `D:\\bench\\album-${String(album).padStart(3, '0')}\\IMG_${String(index).padStart(5, '0')}.jpg`,
      name: `album-${String(album).padStart(3, '0')}/IMG_${String(index).padStart(5, '0')}.jpg`,
      width,
      height,
      takenAt: `${year}-${String(month).padStart(2, '0')}-${String(day).padStart(2, '0')}`,
      dateSource: index % 10 === 1 ? 'mtime' : 'exif',
      mtimeMs: Date.UTC(year, month - 1, day),
      sizeBytes: 2_000_000 + index
    })
  }
  return photos
}

/**
 * Ensure the default fixtures exist under `root`.
 *
 * The 40 000-photo tree is *not* built here: it is 3.6 GB of files that most
 * runs never touch. `ensureLargeLibrary` builds it on demand.
 */
export async function ensureFixtures(
  root: string,
  options: { photos?: number } = {}
): Promise<BenchFixtures> {
  const photos = options.photos ?? 40_000
  await mkdir(root, { recursive: true })
  const templates = await templateDir(root)
  let rebuilt = templates.built

  const samplesDir = join(root, 'samples')
  const sampleMarker: Marker = {
    version: FIXTURE_VERSION,
    kind: 'samples',
    files: SAMPLES_PER_KIND * 4
  }
  if (!(await markerMatches(samplesDir, sampleMarker))) {
    rebuilt = true
    await rm(samplesDir, { recursive: true, force: true })
    await mkdir(samplesDir, { recursive: true })
    const kinds: Array<[string, string, keyof SampleFiles]> = [
      ['exif', 'jpg', 'jpegExif'],
      ['plain', 'jpg', 'jpegPlain'],
      ['shot', 'png', 'pngPlain'],
      ['fat', 'jpg', 'jpegFat']
    ]
    for (const [template, extension, kind] of kinds) {
      for (let index = 0; index < SAMPLES_PER_KIND; index++) {
        await copyFile(
          join(templates.dir, `${template}.${extension}`),
          join(samplesDir, `${kind}-${String(index).padStart(2, '0')}.${extension}`)
        )
      }
    }
    await writeMarker(samplesDir, sampleMarker)
  }

  const listing = (kind: keyof SampleFiles, extension: string): string[] =>
    Array.from({ length: SAMPLES_PER_KIND }, (_, index) =>
      join(samplesDir, `${kind}-${String(index).padStart(2, '0')}.${extension}`)
    )

  const lib4000 = await library(root, templates.dir, `library-${ALBUMS * 1000}`, ALBUMS, 1000)
  rebuilt = rebuilt || lib4000.built

  return {
    root,
    samples: {
      jpegExif: listing('jpegExif', 'jpg'),
      jpegPlain: listing('jpegPlain', 'jpg'),
      pngPlain: listing('pngPlain', 'png'),
      jpegFat: listing('jpegFat', 'jpg')
    },
    lib4000: lib4000.dir,
    album1000: join(lib4000.dir, 'album-000'),
    lib40000: join(root, 'library-40000'),
    large: join(templates.dir, '12mp.jpg'),
    photos40000: syntheticPhotos(photos),
    rebuilt
  }
}

/**
 * Build the 40 000-photo tree on demand. See `ensureFixtures`.
 *
 * Returns whether it had to be built, which the caller uses to warn: a freshly
 * written tree is slower on its first pass, because the virus scanner has not
 * looked at those files before, and a baseline recorded from that pass would be
 * 40% too pessimistic.
 */
export async function ensureLargeLibrary(
  fixtures: BenchFixtures
): Promise<{ dir: string; built: boolean }> {
  return library(
    fixtures.root,
    join(fixtures.root, '_templates'),
    'library-40000',
    ALBUMS,
    10_000
  )
}

/** File size and mtime, as a thumbnail request needs them. */
export async function fileFacts(path: string): Promise<{ mtimeMs: number; sizeBytes: number }> {
  const info = await stat(path)
  return { mtimeMs: info.mtimeMs, sizeBytes: info.size }
}
